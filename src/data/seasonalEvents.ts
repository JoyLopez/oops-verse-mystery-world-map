// Helper to determine active event based on date or custom simulated month
export function getActiveSeasonalEvent(simulatedMonth?: number): SeasonalEvent {
  const currentMonth = simulatedMonth ?? new Date().getMonth() + 1; // 1 to 12

  const active = SEASONAL_EVENTS.find((event) => event.activeMonths.includes(currentMonth));
  return active || SEASONAL_EVENTS[0]; // fallback to Summer Expo
}
